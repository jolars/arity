#!/usr/bin/env Rscript
# Refresh static methods metadata. R is an offline oracle, never a runtime dependency.
stopifnot(Sys.setlocale("LC_COLLATE", "C") == "C")
args <- commandArgs(trailingOnly = TRUE)
out <- if (length(args)) args[[1L]] else file.path("src", "project", "classes", "s4_dispatch")
dir.create(out, recursive = TRUE, showWarnings = FALSE)
header <- sprintf("# generated by scripts/dump_s4_builtins.R from R %s", getRversion())
packed <- function(x) if (length(x)) paste(x, collapse = ",") else "-"
names <- sort(unique(c(ls(baseenv(), all.names = TRUE),
                       as.character(methods::getGenerics(where = asNamespace("methods"))))))
rows <- character()
parameters <- character()
for (name in names) {
    generic <- methods::getGeneric(name)
    if (is.null(generic)) next
    rows <- c(rows, paste(name, generic@package, packed(generic@signature),
                         packed(generic@group), methods::is(generic, "groupGenericFunction"),
                         isTRUE(attr(generic@signature, "simpleOnly")),
                         sep = "\t"))
    formals <- formals(generic)
    for (i in seq_along(formals)) {
        default <- paste(deparse(formals[[i]], width.cutoff = 500L), collapse = " ")
        parameters <- c(parameters, paste(name, generic@package, names(formals)[[i]],
                                           if (nzchar(default)) default else "-", sep = "\t"))
    }
}
writeLines(c(header, rows), file.path(out, "generics.tsv"))
writeLines(c(header, parameters), file.path(out, "formals.tsv"))
callables <- character()
for (package in c("base", "methods")) {
    for (name in sort(getNamespaceExports(package))) {
        value <- getExportedValue(package, name)
        if (is.primitive(value)) {
            kind <- "primitive"
            generic <- methods::getGeneric(value)
        } else if (methods::is(value, "genericFunction")) {
            kind <- "generic"
            generic <- value
        } else {
            next
        }
        if (methods::is(generic, "genericFunction")) {
            callables <- c(callables, paste(package, name, kind, generic@package,
                                             generic@generic, sep = "\t"))
        }
    }
}
writeLines(c(header, callables), file.path(out, "callables.tsv"))
classes <- sort(unique(c(methods::getClasses(where = baseenv()),
                         methods::getClasses(where = asNamespace("methods")))))
rows <- vapply(classes, function(name) {
    definition <- methods::getClassDef(name)
    direct <- names(definition@contains)[vapply(definition@contains, function(parent) {
        parent@distance == 1L
    }, TRUE)]
    paste(name, packed(direct), sep = "\t")
}, "")
writeLines(c(header, rows), file.path(out, "classes.tsv"))
