#!/usr/bin/env Rscript
# Refresh the bundled license names, versions, and exact legacy mappings.
# Run manually after an R upgrade: Rscript scripts/dump_license_db.R
# This script is never run by the build or the linter.

# arity-ignore-file internal-function: R's own database defines these spellings.
out_dir <- file.path("src", "linter", "rules", "packaging")
header <- sprintf("# Generated by scripts/dump_license_db.R from R %s.", getRversion())
db <- tools:::R_license_db()
writeLines(
  c(
    header,
    "# Columns: name, abbreviation, version, short specification; trailing empty columns omitted.",
    sub("\t+$", "", apply(db[, c("Name", "Abbrev", "Version", "SSS")], 1L, paste, collapse = "\t"))
  ),
  file.path(out_dir, "licenses.tsv")
)
db <- tools:::.standardizable_license_specs_db
writeLines(
  c(header, paste(db$ispecs, db$ospecs, sep = "\t")),
  file.path(out_dir, "license_aliases.tsv")
)
