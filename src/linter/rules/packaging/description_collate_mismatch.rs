//! Validate each effective Collate specification against an independent source
//! inventory. R rejects duplicated, ineligible, and unlisted source paths at
//! installation. No autofix can choose a missing file's execution order.

use std::collections::{BTreeMap, BTreeSet};

use rowan::{TextRange, TextSize};

use crate::dcf::collate::collate_entries;
use crate::linter::diagnostic::{Diagnostic, ViolationData};
use crate::linter::rules::{DcfRule, DcfRuleContext, Example};

pub struct DescriptionCollateMismatch;

const EXAMPLES: &[Example] = &[Example {
    caption: "In a package with `R/a.R` and `R/b.R`:",
    source: "Package: mypkg\nVersion: 0.1.0\nCollate: 'a.R' 'missing.R' 'a.R'\n",
}];

impl DcfRule for DescriptionCollateMismatch {
    fn id(&self) -> &'static str {
        "description-collate-mismatch"
    }

    fn description(&self) -> &'static str {
        "Flag Collate specifications that repeat a filename, name an ineligible \
         or nonexistent R source, or omit an eligible source file. R rejects \
         these specifications during installation.\n\nUnix and Windows are \
         checked separately. `Collate.unix` and `Collate.windows` override \
         `Collate` on their respective platforms. Each list must include the \
         eligible files directly in `R/` and in that platform's subdirectory. \
         Filenames must start with an ASCII letter or digit and end in `.R`, \
         `.r`, `.S`, `.s`, or `.q`. Quoted filenames may contain spaces.\n\n\
         The rule uses a disk inventory independent of Collate and stays silent \
         when that inventory is unavailable, including standalone in-memory \
         buffers. Files generated by `configure` must exist before linting the \
         specification.\n\nThere is no autofix: adding a missing file requires \
         choosing its execution order."
    }

    fn examples(&self) -> &'static [Example] {
        EXAMPLES
    }

    fn doc_package(&self) -> &'static [(&'static str, &'static str)] {
        &[("R/a.R", "NULL\n"), ("R/b.R", "NULL\n")]
    }

    fn check_file(&self, ctx: &DcfRuleContext<'_>, sink: &mut Vec<Diagnostic>) {
        let Some(inventory) = ctx.sources else {
            return;
        };
        // A fallback field can fail identically on both platforms. Merge those
        // findings while retaining which installation targets each one affects.
        let mut findings: BTreeMap<(TextSize, TextSize, String), Vec<&str>> = BTreeMap::new();
        for (os, field_name, sources) in [
            ("Unix", "Collate.unix", &inventory.unix),
            ("Windows", "Collate.windows", &inventory.windows),
        ] {
            let Some(field) = ctx
                .document
                .field(field_name)
                .or_else(|| ctx.document.field("Collate"))
            else {
                continue;
            };
            let mut seen = BTreeSet::new();
            let mut report = |range: TextRange, body| {
                findings
                    .entry((range.start(), range.end(), body))
                    .or_default()
                    .push(os);
            };
            for entry in collate_entries(&field) {
                let name = entry.name.to_string();
                let display = super::scalar_field::escape(&name);
                if !seen.insert(name.clone()) {
                    report(
                        entry.range,
                        format!("`{display}` is listed more than once in `{}`", field.name()),
                    );
                }
                if !sources.contains(&name) {
                    report(
                        entry.range,
                        format!(
                            "`{display}` in `{}` does not name an eligible R source",
                            field.name()
                        ),
                    );
                }
            }
            for name in sources.difference(&seen) {
                report(
                    field.name_range(),
                    format!("R source `{name}` is missing from `{}`", field.name()),
                );
            }
        }
        for ((start, end, body), platforms) in findings {
            sink.push(Diagnostic {
                rule: self.id(),
                severity: self.default_severity(),
                path: Default::default(),
                range: TextRange::new(start, end),
                message: ViolationData::new(
                    self.id(),
                    format!("{body} ({})", platforms.join(" and ")),
                ),
                fix: None,
            });
        }
    }
}
